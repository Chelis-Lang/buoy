#!/usr/bin/env bash
# Tasks 10.2, 10.5, 10.8, 10.9, 10.11, 10.12: realize every explicit
# consumer-package digest variant offline from
# `nix/tools/realize-consumer-package.nix`, then run the static, change,
# bind, trace, and publication command families against the reviewed
# positive fixture repository with empty Cargo and Rustup homes and no
# network access.
#
# This is not a `cargo test` target: it requires a local `nix` installation.
# It is invoked by `nix/tools/package-contract.sh --mode blocking`, the single
# registered owner of every consumer-package task body, which the blocking
# `buoy:package-contract` devenv task runs (see `nix/devenv/tasks.nix`)
# immediately after that owner's fast, offline, Nix-free structural check
# (`check-package-contract`) passes. It is therefore part of the resolved
# `devenv test` graph, not independent of it.
#
# "No network access" here is structural rather than sandbox-enforced: each
# realized runtime closure is checked to contain no fetch tool at all, every
# command runs under `env -i` with empty HOME/CARGO_HOME/RUSTUP_HOME and
# black-holed proxy variables, and the package derivation is verified
# (`check-derivation-contract.sh`) to be a sandboxed non-fixed-output
# derivation, so no build or run step can reach a network.
#
# Usage: nix/tools/verify-offline-realization.sh
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
fixture_root="$repo_root/fixtures/content-addressed-bindings/v1/positive"
work_root="$(mktemp -d)"

# Task 10.16: closure size and noncanonical build cost are recorded
# SEPARATELY, in a retained artifact, and are measured -- never hardcoded.
# Both are environment-dependent operator facts, not identity: nothing here
# may enter a canonical digest, a package identity, or any assurance claim.
# The `noncanonical` marker below is the same label every other Nix
# closure/cost report in this repository uses (see `closureReportRunner` in
# `nix/supply-chain.nix`).
#
# Audit round 5, medium finding 7: the RETAINED artifact is never opened for
# writing while checks are still running. Rows accumulate in a staging file
# beside it, and the retained file is replaced by a single atomic `mv` only
# after every blocking check below has passed. A run that fails partway --
# whether at the digest check, the derivation contract, a realization, or any
# command in the offline matrix -- therefore leaves the previously committed
# measurements byte-for-byte untouched instead of truncating them to a bare
# header. `mktemp` creates the staging file in the same directory, so the
# final `mv` is a same-filesystem rename with no partially visible state, and
# the EXIT trap removes the staging file on every failure path.
measurements="$repo_root/nix/measurements/consumer-package-cost-v1.tsv"
measurements_dir="$(dirname "$measurements")"
mkdir -p "$measurements_dir"
staged_measurements="$(mktemp "$measurements_dir/.consumer-package-cost-v1.tsv.XXXXXXXX")"
trap 'rm -rf "$work_root"; rm -f "$staged_measurements"' EXIT
{
  echo "# buoy/consumer-package-cost/v1"
  echo "# NONCANONICAL: environment-dependent measurements only."
  echo "# These rows record closure size and build cost. They are not identity,"
  echo "# never enter a canonical digest or package identity, and establish no"
  echo "# assurance claim. Regenerated by nix/tools/verify-offline-realization.sh."
  printf 'measurement\tvariant\tvalue\tunit\tclassification\n'
} >"$staged_measurements"

# Task 10.5 / audit M13: the source-content digest is a committed, reviewed
# constant. This verification path derives the declared source closure's
# content hash independently and compares it against that constant; it never
# derives the expected value from the tree it is about to build. Realization
# below then declares the same reviewed constant to Nix, whose own
# fixed-output check fails closed on any difference.
"$repo_root/nix/tools/derive-source-content-digest.sh" --verify

# Real derivation-level contract for every variant (PBD-002/PBD-004),
# checked against values Nix computed rather than the package file's text.
"$repo_root/nix/tools/check-derivation-contract.sh"

variants=(xxh3-128 blake3-256 sha-256)

# Instantiate every variant from one consistent view of the declared source
# closure BEFORE any of them builds. Realization then works from those exact
# derivations, so a long build cannot silently pick up a different source
# tree partway through the matrix.
declare -a variant_drvs=()
for variant in "${variants[@]}"; do
  variant_drvs+=("$(nix-instantiate "$repo_root/nix/tools/realize-consumer-package.nix" \
    --argstr digestFeature "$variant" 2>/dev/null)")
done

for index in "${!variants[@]}"; do
  variant="${variants[$index]}"
  echo "== realizing ${variant} =="
  out_link="$work_root/package-${variant}"
  build_started="$SECONDS"
  nix-store --realise "${variant_drvs[$index]}" --add-root "$out_link" --indirect >/dev/null
  build_seconds="$((SECONDS - build_started))"

  binary="$out_link/bin/buoy"
  test -x "$binary"
  installed_commands="$(find "$out_link/bin" -mindepth 1 -maxdepth 1 -exec basename {} \; | LC_ALL=C sort)"
  expected_commands="$(printf '%s\n' buoy buoy-migrate chelis-provenance)"
  if [ "$installed_commands" != "$expected_commands" ]; then
    echo "unexpected installed commands for ${variant}: ${installed_commands}" >&2
    exit 1
  fi
  for command in buoy buoy-migrate chelis-provenance; do
    test -x "$out_link/bin/$command"
  done

  closure_info="$(nix path-info --json --json-format 1 --closure-size "$out_link")"
  nar_bytes="$(printf '%s' "$closure_info" | grep -o '"narSize":[0-9]*' | head -1 | cut -d: -f2)"
  closure_bytes="$(printf '%s' "$closure_info" | grep -o '"closureSize":[0-9]*' | head -1 | cut -d: -f2)"
  {
    printf 'output-nar-size\t%s\t%s\tbytes\tnoncanonical-measurement\n' "$variant" "$nar_bytes"
    printf 'closure-size\t%s\t%s\tbytes\tnoncanonical-measurement\n' "$variant" "$closure_bytes"
    printf 'build-cost\t%s\t%s\tseconds\tnoncanonical-measurement\n' "$variant" "$build_seconds"
  } >>"$staged_measurements"

  # A control hook, never set by any gate: it forces this run to fail PARTWAY
  # -- after this variant's rows are already staged and before the remaining
  # variants are processed -- so a control can observe that the retained
  # `nix/measurements/consumer-package-cost-v1.tsv` is byte-for-byte unchanged
  # after a mid-run failure.
  if [ "${BUOY_FORCE_MEASUREMENT_FAILURE:-}" = "$variant" ]; then
    echo "verify-offline-realization: forced-mid-run-failure ${variant}" >&2
    exit 1
  fi

  # PBD-004, read from the realized store content rather than from the text
  # of any file:
  #
  #   * the launcher is the compiled executable itself, not a wrapper script
  #     that could clone or fetch before each invocation;
  #   * the realized output embeds no host-specific source path; and
  #   * it stores no SSH key, provider token, or other credential.
  #
  # The package excludes the pinned compiler through its output-reference constraint.
  # The compile-time source path map removes its build-only reference.
  # Runtime libraries remain in the closure. These checks do not ban every
  # network client that a runtime library can retain.
  case "$(head -c 2 "$binary")" in
  "#!")
    echo "the packaged launcher must be a compiled executable, not a script wrapper" >&2
    exit 1
    ;;
  esac
  if LC_ALL=C grep -ralF -- "$repo_root" "$out_link" >/dev/null 2>&1; then
    echo "the realized package must embed no host-specific source path" >&2
    exit 1
  fi
  for secret in "BEGIN OPENSSH PRIVATE KEY" "BEGIN RSA PRIVATE KEY" "ssh-rsa AAAA" "ghp_"; do
    if LC_ALL=C grep -ralF -- "$secret" "$out_link" >/dev/null 2>&1; then
      echo "the realized package must store no credential material (${secret})" >&2
      exit 1
    fi
  done

  empty_home="$work_root/home-${variant}"
  empty_cargo="$work_root/cargo-${variant}"
  empty_rustup="$work_root/rustup-${variant}"
  mkdir -p "$empty_home" "$empty_cargo" "$empty_rustup"

  offline_run() {
    env -i HOME="$empty_home" CARGO_HOME="$empty_cargo" RUSTUP_HOME="$empty_rustup" PATH=/usr/bin:/bin \
      http_proxy=http://127.0.0.1:1 https_proxy=http://127.0.0.1:1 all_proxy=http://127.0.0.1:1 \
      HTTP_PROXY=http://127.0.0.1:1 HTTPS_PROXY=http://127.0.0.1:1 ALL_PROXY=http://127.0.0.1:1 "$@"
  }
  static_root="$work_root/static-root-${variant}"
  mkdir -p "$static_root/docs"
  cp -R "$repo_root/examples/repositories/openspec-authority/openspec" "$static_root/openspec"
  static_config="$work_root/static-${variant}.toml"
  sed "s/xxh3-128/${variant}/g" "$repo_root/examples/repositories/openspec-authority/buoy.toml" >"$static_config"
  offline_run "$binary" static --root "$static_root" --config "$static_config" \
    --format machine >"$work_root/authority-${variant}.json"
  atom_revision="$(jq -er '.requirement_subjects[] | select(.id == "DEMO-001") | .atom_revision' \
    "$work_root/authority-${variant}.json")"
  cp -R "$repo_root/examples/repositories/openspec-authority/docs/." "$static_root/docs/"
  sed "s/DEMO-001@xxh3-128:[a-f0-9]*/DEMO-001@${atom_revision}/g" \
    "$repo_root/examples/repositories/openspec-authority/docs/all-relations.md" \
    >"$static_root/docs/all-relations.md"
  offline_run "$binary" static --root "$static_root" \
    --config "$static_config" --format machine >"$work_root/static-${variant}.json"
  jq -e '.diagnostics == [] and .migration.uncovered_atoms == ["DEMO-001"]' \
    "$work_root/static-${variant}.json" >/dev/null

  migration_input="$work_root/migration-input-${variant}.toml"
  sed "s/^target_algorithm = \"xxh3-128\"/target_algorithm = \"${variant}\"/" \
    "$repo_root/fixtures/xxh3/v2/migration/complete-v1-input.toml" >"$migration_input"
  offline_run "$out_link/bin/buoy-migrate" complete \
    "$migration_input" >"$work_root/migration-${variant}.tsv"
  grep -q '^spec-provenance/v3' "$work_root/migration-${variant}.tsv"

  chelis_root="$work_root/chelis-${variant}"
  mkdir -p "$chelis_root/chelis"
  printf '%s\n' 'def smoke(x: f32) -> f32 = x' >"$chelis_root/chelis/smoke.ch"
  printf '%s\n' 'schema = "chelis-adapter-config/v1"' '[[selector]]' 'root = "chelis"' 'dialect = "surf"' \
    >"$chelis_root/config.toml"
  offline_run "$out_link/bin/chelis-provenance" static \
    --root "$chelis_root" --config "$chelis_root/config.toml" >"$work_root/chelis-${variant}.json"
  jq -e '.schema == "chelis-static-report/v3" and .diagnostics == [] and .verdict == "accept"' \
    "$work_root/chelis-${variant}.json" >/dev/null

  identity="$(offline_run "$binary" package-identity)"
  case "$identity" in
    *"\"features\":[\"${variant}\"]"*) ;;
    *)
      echo "package-identity did not report the built variant: $identity" >&2
      exit 1
      ;;
  esac

  if [ "$variant" = "blake3-256" ]; then
    run() {
      offline_run "$binary" "$@"
    }

    static_report="$(run static --root "$fixture_root" --config "$fixture_root/buoy.toml")"
    graph_digest="$(printf '%s' "$static_report" | sed -n 's/.*"graph":"\([^"]*\)".*/\1/p')"
    test -n "$graph_digest"

    trace_report="$(run trace --root "$fixture_root" --config "$fixture_root/buoy.toml" --requirement-id BGLC-003)"

    # A writable copy of the fixture for `bind` and `publication`: both
    # write real bytes (a binding object and a generated page), and the
    # committed fixture under version control must stay read-only.
    writable_root="$work_root/writable-${variant}"
    mkdir -p "$writable_root/buoy/objects/v1/blake3-256"
    cp "$fixture_root/buoy.toml" "$writable_root/buoy.toml"
    cp -R "$fixture_root/openspec" "$writable_root/openspec"
    cp -R "$fixture_root/src" "$writable_root/src"
    cp "$fixture_root/buoy/objects/v1/blake3-256/0e857e33e387325fbf457e426bc42286d9d99926b19f3efa3c203795cfeeb6c4.toml" \
      "$writable_root/buoy/objects/v1/blake3-256/0e857e33e387325fbf457e426bc42286d9d99926b19f3efa3c203795cfeeb6c4.toml"

    # Task 10.9: run a real `bind` invocation offline too, not only
    # static/trace/change/publication. This fixture's BGLC-003 relation is
    # already bound at these exact node digests, so re-running `bind`
    # against the identical requirement/implementation nodes exercises the
    # real offline `bind` command path and its immutable create-if-equal
    # semantics (a no-op success) against the writable copy.
    requirement_node="$(printf '%s' "$trace_report" | sed -n 's/.*"requirement_node":"\([^"]*\)".*/\1/p')"
    implementation_node="$(printf '%s' "$trace_report" | sed -n 's/.*"implementation_node":"\([^"]*\)".*/\1/p')"
    test -n "$requirement_node"
    test -n "$implementation_node"
    run bind --root "$writable_root" --config "$writable_root/buoy.toml" \
      --requirement "$requirement_node" --implementation "$implementation_node" \
      --relation BGLC-RENDER-CATALOG-V2 >/dev/null

    manifest_path="$work_root/manifest-${variant}.toml"
    cat >"$manifest_path" <<MANIFEST
schema = "spec-provenance-change-manifest/v1"
id = "OFFLINE-VERIFY"
base_graph = "${graph_digest}"
head_graph = "${graph_digest}"
dispositions = []
MANIFEST
    run change --base "$fixture_root" --head "$fixture_root" --config "$fixture_root/buoy.toml" --manifest "$manifest_path" >/dev/null

    if run publication evidence --plan /nonexistent.json >/dev/null 2>&1; then
      echo "publication evidence against a missing plan must fail" >&2
      exit 1
    fi

    # A real positive publication sequence against the same writable root:
    # check (absent page returns a static blocker), generate (writes the
    # real page), and check again (equal page succeeds).
    # The exact source-set policy MUST list every currently selected path.
    # The real `bind` invocation above may have just created a SECOND
    # binding-record file (a distinct relation is a distinct content-
    # addressed digest), so the declared policy is computed here, from the
    # writable root's real current file listing, rather than hardcoded to
    # the one binding file that existed before that step ran.
    source_set_json="$(
      cd "$writable_root"
      {
        find openspec/specs -name '*.md'
        find src -name '*.rs'
        find buoy/objects -name '*.toml'
      } | sed 's/.*/"&"/' | paste -sd, -
    )"
    plan_path="$work_root/publication-plan-${variant}.json"
    cat >"$plan_path" <<PLAN
{"schema":"buoy/trace-publication-plan/v1","publication_id":"offline-verify","selector":{"requirement_id":"BGLC-003"},"expected_rows":1,"source_set":[${source_set_json}],"outputs":[{"id":"page","mount":"repository","path":"out/page.md","kind":"page","lifecycle":"replaceable"}]}
PLAN

    if run publication check --plan "$plan_path" --artifact page --config "$writable_root/buoy.toml" --root "$writable_root" >/dev/null 2>&1; then
      echo "an absent publication page must be a static blocker" >&2
      exit 1
    fi
    run publication generate --plan "$plan_path" --artifact page --config "$writable_root/buoy.toml" --root "$writable_root" >/dev/null
    test -f "$writable_root/out/page.md"
    run publication check --plan "$plan_path" --artifact page --config "$writable_root/buoy.toml" --root "$writable_root" >/dev/null
  fi

  echo "== ${variant} ok =="
done

# Every blocking check above passed. Only now does the retained artifact
# change, and it changes in one atomic same-directory rename: no reader can
# ever observe a truncated or half-written measurements file, and no failed
# run can leave one behind.
chmod 0644 "$staged_measurements"
mv -f "$staged_measurements" "$measurements"

echo "== retained closure-size and build-cost measurements (noncanonical) =="
cat "$measurements"
echo "verify-offline-realization: ok variants=${variants[*]}"
